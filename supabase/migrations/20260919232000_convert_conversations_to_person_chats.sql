-- Convert job-scoped conversations into one conversation per user pair.
-- Does not delete messages. Does not change notification trigger types.
-- Does not apply itself; review before running on live.
-- Old conversations/messages RLS policies that reference conversations.job_id
-- must be dropped before DROP COLUMN job_id (no CASCADE).

-- ---------------------------------------------------------------------------
-- 1. New tables and messages.job_id
-- ---------------------------------------------------------------------------

create table if not exists public.conversation_jobs (
  conversation_id bigint not null
    references public.conversations (id)
    on delete cascade,
  job_id bigint not null
    references public.jobs (id)
    on delete cascade,
  created_at timestamptz not null default now(),
  primary key (conversation_id, job_id),
  unique (job_id)
);

create table if not exists public.conversation_events (
  id bigint generated by default as identity primary key,
  conversation_id bigint not null
    references public.conversations (id)
    on delete cascade,
  job_id bigint not null
    references public.jobs (id)
    on delete cascade,
  type text not null
    check (
      type in (
        'offer_sent',
        'offer_accepted',
        'offer_rejected',
        'job_created',
        'job_completed',
        'job_cancelled'
      )
    ),
  actor_id uuid null
    references public.profiles (id)
    on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists conversation_events_conversation_created_idx
  on public.conversation_events (conversation_id, created_at);

create table if not exists public.conversation_migration_map (
  old_conversation_id bigint primary key,
  canonical_conversation_id bigint not null,
  job_id bigint,
  participant_low uuid,
  participant_high uuid
);

alter table public.messages
  add column if not exists job_id bigint
    references public.jobs (id)
    on delete set null;

alter table public.conversations
  add column if not exists participant_low uuid;

alter table public.conversations
  add column if not exists participant_high uuid;

-- ---------------------------------------------------------------------------
-- 2. Validate source data before any merge
-- ---------------------------------------------------------------------------

do $$
declare
  null_job_count integer;
  multi_accepted text;
  missing_provider text;
  self_pair_count integer;
begin
  select count(*)
  into null_job_count
  from public.conversations
  where job_id is null;

  if null_job_count > 0 then
    raise exception
      'Migration aborted: % conversation(s) have null job_id',
      null_job_count;
  end if;

  select string_agg(job_id::text, ', ' order by job_id)
  into multi_accepted
  from (
    select offer.job_id
    from public.offers as offer
    where offer.status = 'accepted'
    group by offer.job_id
    having count(*) > 1
  ) as duplicated;

  if multi_accepted is not null then
    raise exception
      'Migration aborted: multiple accepted offers on job_id(s): %',
      multi_accepted;
  end if;

  select string_agg(conversation.id::text, ', ' order by conversation.id)
  into missing_provider
  from public.conversations as conversation
  where not exists (
    select 1
    from public.offers as offer
    where offer.job_id = conversation.job_id
      and offer.status = 'accepted'
  );

  if missing_provider is not null then
    raise exception
      'Migration aborted: no accepted provider for conversation id(s): %',
      missing_provider;
  end if;

  select count(*)
  into self_pair_count
  from public.conversations as conversation
  inner join public.jobs as job
    on job.id = conversation.job_id
  inner join public.offers as offer
    on offer.job_id = job.id
    and offer.status = 'accepted'
  where job.customer_id = offer.provider_id;

  if self_pair_count > 0 then
    raise exception
      'Migration aborted: % conversation(s) would have participant_low = participant_high',
      self_pair_count;
  end if;
end
$$;

-- ---------------------------------------------------------------------------
-- 3. Backfill participants and messages.job_id
-- ---------------------------------------------------------------------------

update public.conversations as conversation
set
  participant_low = least(job.customer_id, offer.provider_id),
  participant_high = greatest(job.customer_id, offer.provider_id)
from public.jobs as job
inner join public.offers as offer
  on offer.job_id = job.id
  and offer.status = 'accepted'
where job.id = conversation.job_id;

do $$
declare
  unset_count integer;
begin
  select count(*)
  into unset_count
  from public.conversations
  where participant_low is null
     or participant_high is null;

  if unset_count > 0 then
    raise exception
      'Migration aborted: % conversation(s) still missing participants',
      unset_count;
  end if;
end
$$;

update public.messages as message
set job_id = conversation.job_id
from public.conversations as conversation
where message.conversation_id = conversation.id
  and conversation.job_id is not null
  and message.job_id is null;

-- ---------------------------------------------------------------------------
-- 4. Mapping + canonical = min(id) per pair
-- ---------------------------------------------------------------------------

truncate public.conversation_migration_map;

insert into public.conversation_migration_map (
  old_conversation_id,
  canonical_conversation_id,
  job_id,
  participant_low,
  participant_high
)
select
  conversation.id,
  min(conversation.id) over (
    partition by
      conversation.participant_low,
      conversation.participant_high
  ),
  conversation.job_id,
  conversation.participant_low,
  conversation.participant_high
from public.conversations as conversation;

-- ---------------------------------------------------------------------------
-- 5. Move messages to canonical conversations (ids unchanged)
-- ---------------------------------------------------------------------------

update public.messages as message
set conversation_id = migration_map.canonical_conversation_id
from public.conversation_migration_map as migration_map
where message.conversation_id = migration_map.old_conversation_id
  and migration_map.old_conversation_id
    <> migration_map.canonical_conversation_id;

do $$
declare
  leftover integer;
begin
  select count(*)
  into leftover
  from public.messages as message
  inner join public.conversation_migration_map as migration_map
    on migration_map.old_conversation_id = message.conversation_id
  where migration_map.old_conversation_id
    <> migration_map.canonical_conversation_id;

  if leftover > 0 then
    raise exception
      'Migration aborted: % message(s) still on duplicate conversations',
      leftover;
  end if;
end
$$;

-- ---------------------------------------------------------------------------
-- 6. conversation_jobs from every old conversation.job_id
-- ---------------------------------------------------------------------------

insert into public.conversation_jobs (
  conversation_id,
  job_id
)
select distinct
  migration_map.canonical_conversation_id,
  migration_map.job_id
from public.conversation_migration_map as migration_map
where migration_map.job_id is not null
on conflict (job_id) do nothing;

-- ---------------------------------------------------------------------------
-- 7. conversation_reads: MIN cursor, null stays null
-- ---------------------------------------------------------------------------

insert into public.conversation_reads (
  conversation_id,
  user_id,
  last_read_message_id,
  updated_at
)
select
  migration_map.canonical_conversation_id,
  conversation_read.user_id,
  case
    when bool_or(conversation_read.last_read_message_id is null)
      then null
    else min(conversation_read.last_read_message_id)
  end,
  max(conversation_read.updated_at)
from public.conversation_reads as conversation_read
inner join public.conversation_migration_map as migration_map
  on migration_map.old_conversation_id = conversation_read.conversation_id
group by
  migration_map.canonical_conversation_id,
  conversation_read.user_id
on conflict (conversation_id, user_id)
do update set
  last_read_message_id = excluded.last_read_message_id,
  updated_at = excluded.updated_at;

delete from public.conversation_reads as conversation_read
using public.conversation_migration_map as migration_map
where conversation_read.conversation_id =
    migration_map.old_conversation_id
  and migration_map.old_conversation_id <>
    migration_map.canonical_conversation_id;

-- ---------------------------------------------------------------------------
-- 8. notifications.conversation_id → canonical (types unchanged)
-- ---------------------------------------------------------------------------

update public.notifications as notification
set conversation_id = migration_map.canonical_conversation_id
from public.conversation_migration_map as migration_map
where notification.conversation_id = migration_map.old_conversation_id
  and migration_map.old_conversation_id
    <> migration_map.canonical_conversation_id;

-- ---------------------------------------------------------------------------
-- 9. Remove duplicate conversation rows (messages already moved)
-- ---------------------------------------------------------------------------

do $$
declare
  message_count_before integer;
  message_count_after integer;
begin
  select count(*) into message_count_before from public.messages;

  delete from public.conversations as conversation
  using public.conversation_migration_map as migration_map
  where conversation.id = migration_map.old_conversation_id
    and migration_map.old_conversation_id
      <> migration_map.canonical_conversation_id;

  select count(*) into message_count_after from public.messages;

  if message_count_after <> message_count_before then
    raise exception
      'Migration aborted: message count changed from % to %',
      message_count_before,
      message_count_after;
  end if;
end
$$;

