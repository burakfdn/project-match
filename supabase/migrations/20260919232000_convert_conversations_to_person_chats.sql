-- conversation_reads: keep existing own-row SELECT; writes stay on RPC.

do $$
declare
  conversation_count integer;
  pair_count integer;
  mapped_jobs integer;
  linked_jobs integer;
begin
  select count(*) into conversation_count from public.conversations;
  select count(*) into pair_count
  from (
    select participant_low, participant_high
    from public.conversations
    group by participant_low, participant_high
  ) as pairs;

  if conversation_count <> pair_count then
    raise exception
      'Migration aborted: conversation count % != unique pair count %',
      conversation_count,
      pair_count;
  end if;

  select count(distinct job_id)
  into mapped_jobs
  from public.conversation_migration_map
  where job_id is not null;

  select count(*)
  into linked_jobs
  from public.conversation_jobs;

  if linked_jobs <> mapped_jobs then
    raise exception
      'Migration aborted: conversation_jobs % != mapped jobs %',
      linked_jobs,
      mapped_jobs;
  end if;

  if exists (
    select 1
    from public.conversation_migration_map as migration_map
    where migration_map.job_id is not null
      and not exists (
        select 1
        from public.conversation_jobs as conversation_job
        where conversation_job.job_id = migration_map.job_id
          and conversation_job.conversation_id
            = migration_map.canonical_conversation_id
      )
  ) then
    raise exception
      'Migration aborted: conversation_jobs mapping mismatch';
  end if;

  if exists (
    select 1
    from (
      select distinct
        migration_map.job_id,
        migration_map.canonical_conversation_id
      from public.conversation_migration_map as migration_map
      where migration_map.job_id is not null
    ) as expected_job
    where (
      select count(*)
      from public.conversation_jobs as conversation_job
      where conversation_job.job_id = expected_job.job_id
    ) <> 1
    or not exists (
      select 1
      from public.conversation_jobs as conversation_job
      where conversation_job.job_id = expected_job.job_id
        and conversation_job.conversation_id
          = expected_job.canonical_conversation_id
    )
  ) then
    raise exception
      'Migration aborted: conversation_jobs mapping mismatch';
  end if;
end
$$;
