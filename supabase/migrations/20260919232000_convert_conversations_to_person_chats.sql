create or replace function public.can_access_conversation(
  p_conversation_id bigint
)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    return false;
  end if;

  return exists (
    select 1
    from public.conversations as conversation
    where conversation.id = p_conversation_id
      and current_user_id in (
        conversation.participant_low,
        conversation.participant_high
      )
      and exists (
        select 1
        from public.conversation_jobs as conversation_job
        inner join public.jobs as job
          on job.id = conversation_job.job_id
        where conversation_job.conversation_id = conversation.id
          and (
            job.customer_id = current_user_id
            or exists (
              select 1
              from public.offers as offer
              where offer.job_id = job.id
                and offer.status = 'accepted'
                and offer.provider_id = current_user_id
            )
          )
      )
  );
end;
$$;

create or replace function public.get_or_create_conversation(
  p_job_id bigint
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  job_customer_id uuid;
  job_provider_id uuid;
  pair_low uuid;
  pair_high uuid;
  conversation_id bigint;
begin
  if current_user_id is null then
    raise exception 'Oturum bulunamadı.';
  end if;

  select job.customer_id
  into job_customer_id
  from public.jobs as job
  where job.id = p_job_id;

  if job_customer_id is null then
    raise exception 'İş bulunamadı.';
  end if;

  select offer.provider_id
  into job_provider_id
  from public.offers as offer
  where offer.job_id = p_job_id
    and offer.status = 'accepted';

  if job_provider_id is null then
    raise exception 'Sohbet için kabul edilmiş uzman yok.';
  end if;

  if job_customer_id = job_provider_id then
    raise exception 'Sohbet oluşturulamadı.';
  end if;

  if current_user_id is distinct from job_customer_id
    and current_user_id is distinct from job_provider_id
  then
    raise exception 'Bu konuşmaya erişim yetkiniz yok.';
  end if;

  pair_low := least(job_customer_id, job_provider_id);
  pair_high := greatest(job_customer_id, job_provider_id);

  insert into public.conversations (
    participant_low,
    participant_high
  )
  values (
    pair_low,
    pair_high
  )
  on conflict (participant_low, participant_high)
  do update set
    created_at = public.conversations.created_at
  returning id
  into conversation_id;

  insert into public.conversation_jobs (
    conversation_id,
    job_id
  )
  values (
    conversation_id,
    p_job_id
  )
  on conflict (job_id) do nothing;

  return conversation_id;
end;
$$;

create or replace function public.send_message(
  p_conversation_id bigint,
  p_message text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  message_id bigint;
begin
  if current_user_id is null then
    raise exception 'Oturum bulunamadı.';
  end if;

  if coalesce(nullif(btrim(p_message), ''), '') = '' then
    raise exception 'Boş mesaj gönderilemez.';
  end if;

  if coalesce(
    public.can_access_conversation(p_conversation_id),
    false
  ) is not true then
    raise exception 'Bu konuşmaya erişim yetkiniz yok.';
  end if;

  insert into public.messages (
    conversation_id,
    sender_id,
    message
  )
  values (
    p_conversation_id,
    current_user_id,
    p_message
  )
  returning id into message_id;

  return message_id;
end;
$$;

create or replace function public.get_my_conversations()
returns table (
  conversation_id bigint,
  job_id bigint,
  job_title text,
  other_user_id uuid,
  other_user_name text,
  last_message text,
  last_message_at timestamptz,
  unread_count integer
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'Oturum bulunamadı.';
  end if;

  return query
  select
    conversation.id,
    latest_job.id,
    latest_job.title,
    case
      when conversation.participant_low = current_user_id
        then conversation.participant_high
      else conversation.participant_low
    end,
    nullif(btrim(other_profile.full_name), ''),
    last_msg.message,
    coalesce(last_msg.created_at, conversation.created_at),
    (
      select count(*)::integer
      from public.messages as unread_message
      where unread_message.conversation_id = conversation.id
        and unread_message.sender_id <> current_user_id
        and (
          conversation_read.last_read_message_id is null
          or unread_message.id > conversation_read.last_read_message_id
        )
    )
  from public.conversations as conversation
  left join lateral (
    select job.id, job.title
    from public.conversation_jobs as conversation_job
    inner join public.jobs as job
      on job.id = conversation_job.job_id
    where conversation_job.conversation_id = conversation.id
    order by conversation_job.created_at desc, job.id desc
    limit 1
  ) as latest_job on true
  left join lateral (
    select msg.message, msg.created_at
    from public.messages as msg
    where msg.conversation_id = conversation.id
    order by msg.created_at desc, msg.id desc
    limit 1
  ) as last_msg on true
  left join public.conversation_reads as conversation_read
    on conversation_read.conversation_id = conversation.id
    and conversation_read.user_id = current_user_id
  left join public.profiles as other_profile
    on other_profile.id = case
      when conversation.participant_low = current_user_id
        then conversation.participant_high
      else conversation.participant_low
    end
  where public.can_access_conversation(conversation.id)
  order by coalesce(last_msg.created_at, conversation.created_at) desc;
end;
$$;

