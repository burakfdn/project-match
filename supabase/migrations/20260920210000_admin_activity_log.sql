create or replace function public.admin_activity_log_reviews()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor_role text;
begin
  v_actor_role := case
    when new.reviewer_role in ('customer', 'provider') then new.reviewer_role
    else null
  end;

  if tg_op = 'INSERT' then
    if new.skipped then
      perform public.log_activity_event(
        'review.skipped',
        v_actor_role,
        'review',
        new.id,
        null,
        new.job_id,
        jsonb_build_object('skipped', true)
      );
    else
      perform public.log_activity_event(
        'review.submitted',
        v_actor_role,
        'review',
        new.id,
        null,
        new.job_id,
        jsonb_build_object(
          'skipped', false,
          'rating', new.rating
        )
      );
    end if;
  end if;

  if tg_op = 'UPDATE'
    and old.published_at is null
    and new.published_at is not null
  then
    perform public.log_activity_event(
      'review.published',
      v_actor_role,
      'review',
      new.id,
      null,
      new.job_id,
      jsonb_build_object('skipped', new.skipped)
    );
  end if;

  return new;
exception
  when others then
    raise warning 'admin_activity_log_reviews failed: %', sqlerrm;
    return new;
end;
$$;

