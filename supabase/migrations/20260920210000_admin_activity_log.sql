create or replace function public.admin_activity_log_messages()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_job_id bigint;
  v_actor_role text;
begin
  select conversation_job.job_id
  into v_job_id
  from public.conversation_jobs as conversation_job
  where conversation_job.conversation_id = new.conversation_id
  order by conversation_job.created_at desc
  limit 1;

  select case
    when job.customer_id = new.sender_id then 'customer'
    else 'provider'
  end
  into v_actor_role
  from public.jobs as job
  where job.id = v_job_id;

  perform public.log_activity_event(
    'message.sent',
    v_actor_role,
    'message',
    new.id,
    null,
    v_job_id,
    jsonb_build_object(
      'conversation_id', new.conversation_id,
      'content_length', char_length(coalesce(new.message, '')),
      'job_id', v_job_id
    )
  );

  return new;
exception
  when others then
    raise warning 'admin_activity_log_messages failed: %', sqlerrm;
    return new;
end;
$$;

drop trigger if exists admin_activity_log_messages_insert on public.messages;
create trigger admin_activity_log_messages_insert
  after insert on public.messages
  for each row
  execute procedure public.admin_activity_log_messages();

create or replace function public.admin_activity_log_profiles()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor_id uuid := auth.uid();
  v_actor_is_admin boolean := false;
  v_flags_changed boolean := false;
begin
  if old.full_name is distinct from new.full_name then
    perform public.log_activity_event(
      'profile.name_updated',
      case
        when new.provider_enabled and not new.customer_enabled then 'provider'
        else 'customer'
      end,
      'profile',
      null,
      new.id,
      null,
      '{}'::jsonb
    );
  end if;

  v_flags_changed :=
    old.customer_enabled is distinct from new.customer_enabled
    or old.provider_enabled is distinct from new.provider_enabled
    or old.is_admin is distinct from new.is_admin;

  if not v_flags_changed then
    return new;
  end if;

  select coalesce(profile.is_admin, false)
  into v_actor_is_admin
  from public.profiles as profile
  where profile.id = v_actor_id;

  if v_actor_is_admin
    and (
      v_actor_id is distinct from new.id
      or old.is_admin is distinct from new.is_admin
    )
  then
    perform public.log_activity_event(
      'admin.permissions_updated',
      'admin',
      'admin',
      null,
      new.id,
      null,
      jsonb_build_object(
        'target_user_id', new.id,
        'customer_enabled', new.customer_enabled,
        'provider_enabled', new.provider_enabled,
        'is_admin', new.is_admin
      )
    );
  elsif v_actor_id = new.id
    and (
      old.customer_enabled is distinct from new.customer_enabled
      or old.provider_enabled is distinct from new.provider_enabled
    )
  then
    perform public.log_activity_event(
      'profile.account_type_changed',
      case
        when new.provider_enabled and not new.customer_enabled then 'provider'
        else 'customer'
      end,
      'profile',
      null,
      new.id,
      null,
      jsonb_build_object(
        'customer_enabled', new.customer_enabled,
        'provider_enabled', new.provider_enabled
      )
    );
  end if;

  return new;
exception
  when others then
    raise warning 'admin_activity_log_profiles failed: %', sqlerrm;
    return new;
end;
$$;

drop trigger if exists admin_activity_log_profiles_update on public.profiles;
create trigger admin_activity_log_profiles_update
  after update on public.profiles
  for each row
  execute procedure public.admin_activity_log_profiles();

create or replace function public.admin_list_activity_events(
  p_limit integer default 50,
  p_offset integer default 0,
  p_event_type text default null,
  p_actor_id uuid default null,
  p_job_id bigint default null
)
returns table (
  id bigint,
  occurred_at timestamptz,
  actor_id uuid,
  actor_role text,
  actor_name text,
  event_type text,
  entity_type text,
  entity_id bigint,
  entity_uuid uuid,
  job_id bigint,
  job_title text,
  job_public_id uuid,
  metadata jsonb
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  v_limit integer;
  v_offset integer;
begin
  if current_user_id is null then
    raise exception 'Giriş yapmalısın.';
  end if;

  if not exists (
    select 1
    from public.profiles as profile
    where profile.id = current_user_id
      and profile.is_admin = true
  ) then
    raise exception 'Bu işlem için admin yetkisi gerekir.';
  end if;

  v_limit := least(greatest(coalesce(p_limit, 50), 1), 100);
  v_offset := greatest(coalesce(p_offset, 0), 0);

  return query
  select
    event.id,
    event.occurred_at,
    event.actor_id,
    event.actor_role,
    nullif(btrim(actor.full_name), ''),
    event.event_type,
    event.entity_type,
    event.entity_id,
    event.entity_uuid,
    event.job_id,
    job.title,
    job.public_id,
    event.metadata
  from public.admin_activity_events as event
  left join public.profiles as actor
    on actor.id = event.actor_id
  left join public.jobs as job
    on job.id = event.job_id
  where (
      p_event_type is null
      or btrim(p_event_type) = ''
      or event.event_type = btrim(p_event_type)
    )
    and (
      p_actor_id is null
      or event.actor_id = p_actor_id
    )
    and (
      p_job_id is null
      or event.job_id = p_job_id
    )
  order by event.occurred_at desc, event.id desc
  limit v_limit
  offset v_offset;
end;
$$;

revoke all on function public.admin_list_activity_events(
  integer, integer, text, uuid, bigint
) from public, anon;

grant execute on function public.admin_list_activity_events(
  integer, integer, text, uuid, bigint
) to authenticated;
