-- Admin activity archive.
-- Append-only log of important user/system actions.
-- Does not change matching, RLS, offers, reviews, chat,
-- cancellation, public_id, or existing RPC signatures.

create table if not exists public.admin_activity_events (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  actor_id uuid null,
  actor_role text null,
  event_type text not null,
  entity_type text null,
  entity_id bigint null,
  entity_uuid uuid null,
  job_id bigint null,
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists admin_activity_events_occurred_at_id_idx
  on public.admin_activity_events (occurred_at desc, id desc);

create index if not exists admin_activity_events_event_type_idx
  on public.admin_activity_events (event_type);

create index if not exists admin_activity_events_actor_id_idx
  on public.admin_activity_events (actor_id);

create index if not exists admin_activity_events_job_id_idx
  on public.admin_activity_events (job_id);

alter table public.admin_activity_events enable row level security;
alter table public.admin_activity_events force row level security;

revoke all on table public.admin_activity_events
  from public, anon, authenticated;

create or replace function public.log_activity_event(
  p_event_type text,
  p_actor_role text default null,
  p_entity_type text default null,
  p_entity_id bigint default null,
  p_entity_uuid uuid default null,
  p_job_id bigint default null,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor_id uuid := auth.uid();
  v_actor_role text;
begin
  if p_event_type is null or btrim(p_event_type) = '' then
    return;
  end if;

  v_actor_role := case
    when p_actor_role in ('customer', 'provider', 'admin', 'system')
      then p_actor_role
    else null
  end;

  if v_actor_role = 'admin' then
    if not exists (
      select 1
      from public.profiles as profile
      where profile.id = v_actor_id
        and profile.is_admin = true
    ) then
      return;
    end if;
  end if;

  if v_actor_role = 'system' then
    v_actor_id := null;
  end if;

  insert into public.admin_activity_events (
    actor_id,
    actor_role,
    event_type,
    entity_type,
    entity_id,
    entity_uuid,
    job_id,
    metadata
  ) values (
    v_actor_id,
    v_actor_role,
    btrim(p_event_type),
    p_entity_type,
    p_entity_id,
    p_entity_uuid,
    p_job_id,
    coalesce(p_metadata, '{}'::jsonb)
  );
exception
  when others then
    raise warning 'log_activity_event failed: %', sqlerrm;
end;
$$;

revoke all on function public.log_activity_event(
  text, text, text, bigint, uuid, bigint, jsonb
) from public, anon, authenticated;

create or replace function public.admin_activity_log_jobs()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    perform public.log_activity_event(
      'job.created',
      'customer',
      'job',
      new.id,
      null,
      new.id,
      jsonb_build_object('status', new.status)
    );
    return new;
  end if;

  if old.status is distinct from new.status then
    if new.status = 'cancelled' then
      perform public.log_activity_event(
        'job.cancelled',
        'customer',
        'job',
        new.id,
        null,
        new.id,
        jsonb_build_object(
          'from_status', old.status,
          'to_status', new.status,
          'cancellation_reason', new.cancellation_reason
        )
      );
    elsif new.status = 'completed' then
      perform public.log_activity_event(
        'job.completed',
        'customer',
        'job',
        new.id,
        null,
        new.id,
        jsonb_build_object(
          'from_status', old.status,
          'to_status', new.status
        )
      );
    end if;

    return new;
  end if;

  if old.title is distinct from new.title
    or old.description is distinct from new.description
    or old.budget is distinct from new.budget
    or old.city is distinct from new.city
    or old.location_type is distinct from new.location_type
    or old.deadline is distinct from new.deadline
    or old.service_id is distinct from new.service_id
  then
    perform public.log_activity_event(
      'job.updated',
      'customer',
      'job',
      new.id,
      null,
      new.id,
      jsonb_build_object('status', new.status)
    );
  end if;

  return new;
exception
  when others then
    raise warning 'admin_activity_log_jobs failed: %', sqlerrm;
    return new;
end;
$$;

drop trigger if exists admin_activity_log_jobs_insert on public.jobs;
create trigger admin_activity_log_jobs_insert
  after insert on public.jobs
  for each row
  execute procedure public.admin_activity_log_jobs();

drop trigger if exists admin_activity_log_jobs_update on public.jobs;
create trigger admin_activity_log_jobs_update
  after update on public.jobs
  for each row
  execute procedure public.admin_activity_log_jobs();

